import fs from 'fs';
import path from 'path';

const indexPath = path.join(process.cwd(), 'public', 'index.html');

if (!fs.existsSync(indexPath)) {
  console.error('لم أجد الملف public/index.html — شغّل السكربت من جذر المشروع.');
  process.exit(1);
}

let html = fs.readFileSync(indexPath, 'utf8');
const original = html;
const backupPath = indexPath + '.backup-before-remove-home-adwar';
if (!fs.existsSync(backupPath)) {
  fs.writeFileSync(backupPath, original, 'utf8');
}

// هدف هذا السكربت: إزالة كلمة/عبارة "الأدوار" من قسم الرئيسية فقط،
// وترك قسم كأس العالم 2026 وملفات التحديث كل ربع ساعة كما هي.
// لذلك لا يلمس .github ولا public/worldcup-2026 ولا أي ملفات JSON.

const replacements = [
  // نص بطاقة كأس العالم في الصفحة الرئيسية.
  [
    'تابع مباريات ونتائج كأس العالم، ترتيب المجموعات، مشوار الأردن، والأدوار الإقصائية بتوقيت الأردن.',
    'تابع مباريات ونتائج كأس العالم، مشوار الأردن، وأحدث التحديثات بتوقيت الأردن.'
  ],
  [
    'تابع مباريات ونتائج كأس العالم، ترتيب المجموعات، مشوار الأردن، و الأدوار الإقصائية بتوقيت الأردن.',
    'تابع مباريات ونتائج كأس العالم، مشوار الأردن، وأحدث التحديثات بتوقيت الأردن.'
  ],
  [
    'تابع مباريات ونتائج كأس العالم، ترتيب المجموعات، مشوار الأردن والأدوار الإقصائية بتوقيت الأردن.',
    'تابع مباريات ونتائج كأس العالم، مشوار الأردن، وأحدث التحديثات بتوقيت الأردن.'
  ],
  // بدائل احتياطية إذا كان النص مفصولاً أو منسقاً داخل وسوم HTML.
  ['، والأدوار الإقصائية بتوقيت الأردن', ' بتوقيت الأردن'],
  ['، و الأدوار الإقصائية بتوقيت الأردن', ' بتوقيت الأردن'],
  [' والأدوار الإقصائية بتوقيت الأردن', ' بتوقيت الأردن'],
  ['، والأدوار الإقصائية', ''],
  ['، و الأدوار الإقصائية', ''],
  [' والأدوار الإقصائية', ''],
];

for (const [from, to] of replacements) {
  html = html.split(from).join(to);
}

// نظافة مسافات وعلامات ترقيم ممكنة بعد الحذف.
html = html
  .replace(/،\s*،/g, '،')
  .replace(/\s+،/g, '،')
  .replace(/،\s*\./g, '.')
  .replace(/\s{2,}/g, ' ');

if (html === original) {
  console.log('لم أجد عبارة الأدوار في نص الرئيسية، ولم أغيّر الملف.');
} else {
  fs.writeFileSync(indexPath, html, 'utf8');
  console.log('تم حذف الأدوار من قسم الرئيسية فقط.');
  console.log('تم إنشاء نسخة احتياطية:', backupPath);
}
